#!/usr/bin/env python3
"""Generate aicwf_fw_data.c: the AIC8800 firmware files as C arrays.

usage:
  gen_fwdata.py --src <dir> --out <aicwf_fw_data.c> <relative path>...
  gen_fwdata.py --stub --out <aicwf_fw_data.c>

<dir> holds the files at their repository paths (usb/aic8800D80/..., usb/aic8800DC/...);
they are published at run time as <AIC8800_WIFI_FIRMWARE_PATH>/<family>/<name>
(shim/aicwf_fw_files.c). Every aic_userconfig_*.txt TX power entry (lvl_*) is capped at
TXPWR_MAX dBm, as the Linux image does (firmware/aic8800-intree.sh).
"""
import argparse
import os
import re
import sys

TXPWR_MAX = 15


def cap_userconfig(data, name):
    out, capped = [], 0
    for line in data.decode("latin-1").split("\n"):
        m = re.match(r"^(lvl_[A-Za-z0-9_]+)=(-?\d+)(.*)$", line)
        if m and int(m.group(2)) > TXPWR_MAX:
            line = "%s=%d%s" % (m.group(1), TXPWR_MAX, m.group(3))
            capped += 1
        out.append(line)
    text = "\n".join(out)
    if not re.search(r"^lvl_", text, re.M):
        # the plain AIC8800 userconfig has no per-rate power table: nothing to cap
        print("%s: no lvl_ entries, kept as is" % name, file=sys.stderr)
        return data
    for m in re.finditer(r"^lvl_[A-Za-z0-9_]+=(-?\d+)", text, re.M):
        if int(m.group(1)) > TXPWR_MAX:
            sys.exit("%s: cap failed" % name)
    header = "# Pluto Nano: every lvl_* TX power entry capped at %d dBm (%d changed)\n" % (
        TXPWR_MAX, capped)
    return (header + text).encode("latin-1")


def symbol(path):
    return "aicwf_fw_" + re.sub(r"[^A-Za-z0-9]", "_", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src")
    ap.add_argument("--out", required=True)
    ap.add_argument("--stub", action="store_true")
    ap.add_argument("files", nargs="*")
    a = ap.parse_args()

    parts = ["""/*
 * Generated by rtos/libbsd/aic8800/gen_fwdata.py. Do not edit, do not commit.
 * AIC8800 firmware from github.com/canmv-k230/aic8800_fw (vendor terms, not covered by
 * the driver's licence), published under the RT-Smart firmware path at run time.
 */
#include <stddef.h>
#include <stdint.h>

struct aicwf_fw_file {
\tconst char *path;
\tconst uint8_t *data;
\tsize_t size;
};
"""]
    entries = []
    if not a.stub:
        if not a.src or not a.files:
            sys.exit("--src and files required")
        for rel in a.files:
            with open(os.path.join(a.src, rel), "rb") as f:
                data = f.read()
            name = os.path.basename(rel)
            if name.startswith("aic_userconfig"):
                data = cap_userconfig(data, rel)
            # published path: <family>/<name> (the transport directory is dropped)
            pub = "/".join(rel.split("/")[-2:])
            sym = symbol(pub)
            lines = ["static const uint8_t %s[%d] __attribute__((aligned(8))) = {"
                     % (sym, len(data))]
            for i in range(0, len(data), 16):
                lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
            lines.append("};")
            parts.append("\n".join(lines))
            entries.append('\t{ "%s", %s, %d },' % (pub, sym, len(data)))
    if entries:
        parts.append("const struct aicwf_fw_file aicwf_fw_files[] = {\n%s\n};"
                     % "\n".join(entries))
    else:
        parts.append("const struct aicwf_fw_file aicwf_fw_files[1] = { { NULL, NULL, 0 } };")
    parts.append("const size_t aicwf_fw_file_count = %d;" % len(entries))
    tmp = a.out + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n\n".join(parts) + "\n")
    os.replace(tmp, a.out)
    print("aicwf: wrote %s (%d firmware files)" % (a.out, len(entries)))


if __name__ == "__main__":
    main()
