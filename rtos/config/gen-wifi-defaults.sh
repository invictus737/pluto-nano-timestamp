#!/bin/sh
# Writes the build-time Wi-Fi default header (first boot seed) from NEXUS_WIFI_SSID and
# NEXUS_WIFI_PSK (CI secrets). The values never appear on a command line or in the log; bytes are
# stored XOR 0x5a (keeps them out of a plain `strings` of the image, it is no encryption).
# Empty SSID = no default. usage: gen-wifi-defaults.sh <out.h>
set -eu
OUT=${1:?output header}
TMP="$OUT.tmp.$$"
arr() { # name, value: C byte array of value XOR 0x5a
	printf 'static const unsigned char %s[] = {' "$1"
	printf '%s' "$2" | od -An -v -tu1 | tr -s ' \n' '\n\n' | grep -v '^$' |
		while read -r b; do printf '0x%02x,' $((b ^ 0x5a)); done
	printf '0x00};\n'
}
SSID=${NEXUS_WIFI_SSID:-}
PSK=${NEXUS_WIFI_PSK:-}
[ -n "$SSID" ] || PSK=
{
	echo '/* generated by rtos/config/gen-wifi-defaults.sh: do not commit, do not edit */'
	echo "#define NEXUS_WIFI_DEFAULT_SSID_LEN $(printf '%s' "$SSID" | wc -c | tr -d ' ')"
	echo "#define NEXUS_WIFI_DEFAULT_PSK_LEN $(printf '%s' "$PSK" | wc -c | tr -d ' ')"
	arr nexus_wifi_default_ssid "$SSID"
	arr nexus_wifi_default_psk "$PSK"
} > "$TMP"
if [ -f "$OUT" ] && cmp -s "$TMP" "$OUT"; then rm -f "$TMP"; else mv "$TMP" "$OUT"; fi
[ -n "$SSID" ] && echo "wifi defaults: SSID set ($(printf '%s' "$SSID" | wc -c | tr -d ' ') bytes)" || echo "wifi defaults: none"
